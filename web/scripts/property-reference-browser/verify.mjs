import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
const require = createRequire(process.env.PEAR_BROWSER_TOOLS_PACKAGE || import.meta.url);
const { chromium } = require('@playwright/test');
const { build } = require('esbuild');
const web = fileURLToPath(new URL('../../', import.meta.url));
import { createServer } from 'node:http';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const dir = resolve(process.env.PEAR_PROPERTY_EVIDENCE || '/tmp/pear-property-reference-visual');
await mkdir(dir,{recursive:true});
await build({absWorkingDir:web, entryPoints:['scripts/property-reference-browser/app.tsx'],bundle:true,platform:'browser',format:'esm',tsconfig:'tsconfig.json',outfile:`${dir}/app.js`});
execFileSync('pnpm',['exec','tailwindcss','-i','scripts/property-reference-browser/style.css','-o',`${dir}/style.css`,'--content','scripts/property-reference-browser/app.tsx,src/components/LongTextProperty.tsx,src/components/component-renderers/PropertyReferenceView.tsx'],{cwd:web,stdio:'inherit'});
await writeFile(`${dir}/index.html`,await readFile(new URL('./index.html',import.meta.url)));
await mkdir(`${dir}/screenshots`,{recursive:true});
const server=createServer(async(req,res)=>{try{const file=req.url?.endsWith('.js')?'app.js':req.url?.endsWith('.css')?'style.css':'index.html';res.setHeader('Content-Type',file.endsWith('.js')?'text/javascript':file.endsWith('.css')?'text/css':'text/html');res.end(await readFile(`${dir}/${file}`));}catch{res.statusCode=404;res.end();}});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1280,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto(`http://127.0.0.1:${server.address().port}`);
 await page.getByRole('heading',{name:'Project overview'}).waitFor();
 await page.screenshot({path:`${dir}/screenshots/desktop.png`,fullPage:true});
 await page.getByRole('button',{name:'Show more',exact:true}).click();
 await page.getByRole('button',{name:'Edit property',exact:true}).first().click();
 await page.getByRole('textbox',{name:'Summary',exact:true}).fill('Edited multiline summary\n\nThe second paragraph remains readable.');
 await page.getByRole('button',{name:'Save',exact:true}).click();
 assert((await page.getByLabel('Property reference',{exact:true}).textContent()).includes('Edited multiline summary\n\nThe second paragraph'));
 await page.getByRole('button',{name:'Record B',exact:true}).click();
 assert((await page.getByLabel('Property reference',{exact:true}).textContent()).includes('A second record with its own summary'));
 await page.getByLabel('Property reference',{exact:true}).focus();
 await page.getByRole('button',{name:'Reference settings',exact:true}).click();
 await page.getByLabel('Choose a page',{exact:true}).check();
 await page.getByLabel('Source page',{exact:true}).selectOption('11');
 await page.getByLabel('Property',{exact:true}).selectOption('7');
 await page.screenshot({path:`${dir}/screenshots/picker-desktop.png`,fullPage:true});
 await page.getByRole('button',{name:'Save reference',exact:true}).click();
 assert((await page.getByLabel('Property reference',{exact:true}).textContent()).includes('Edited multiline summary'));
 await page.reload();
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('reference')));
 assert.equal(saved.binding.recordId,'11');assert(!('value' in saved));
 await page.getByRole('button',{name:'Record B',exact:true}).click();
 assert((await page.getByLabel('Property reference',{exact:true}).textContent()).includes('The garden is ready'));
 await page.getByLabel('Property reference',{exact:true}).focus();
 await page.getByRole('button',{name:'Open source',exact:true}).click();
 assert.equal(new URL(page.url()).pathname,'/workspace/local/11');
 await page.goBack();assert.equal(new URL(page.url()).pathname,'/');
 await page.getByRole('button',{name:'Read only',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Reference settings',exact:true}).count(),0);
 assert.equal(await page.getByRole('button',{name:'Edit property',exact:true}).count(),0);
 await page.getByRole('button',{name:'Revoke source',exact:true}).click();
 assert(!(await page.getByLabel('Property reference',{exact:true}).textContent()).includes('The garden'));
 await page.getByRole('button',{name:'Restore access',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Record A',exact:true}).click();
 await page.screenshot({path:`${dir}/screenshots/narrow.png`,fullPage:true});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await page.getByLabel('Property reference',{exact:true}).focus();
 await page.getByRole('button',{name:'Reference settings',exact:true}).click();
 await page.screenshot({path:`${dir}/screenshots/picker-narrow.png`,fullPage:true});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 assert.deepEqual(errors,[]);
 await writeFile(`${dir}/result.json`,JSON.stringify({passed:true,viewportWidths:[1280,390],checks:['multiline edit','self context switch','explicit selection','save/reload','canonical source URL','Back history','read-only controls','revocation and restoration','no horizontal overflow','no browser errors']},null,2));
 console.log('PASS: desktop/narrow visual checks, live edit, self/explicit picker, reload, source navigation/Back, read-only controls and revocation');
}finally{await browser.close();server.close();}
