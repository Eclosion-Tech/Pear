    #[test]
    fn automation_job_nonce_round_trips() {
        let nonce = automation_job_nonce(42, 7);
        assert_eq!(nonce, "automation-q42-a7");
        assert_eq!(parse_automation_nonce(&nonce), Some((42, 7)));
        // Jobs from chat/editor (no nonce, or a `delegate` nonce) are not ours.
        assert_eq!(parse_automation_nonce(""), None);
        assert_eq!(parse_automation_nonce("delegate-1234"), None);
        assert_eq!(parse_automation_nonce("automation-q1"), None);
        assert_eq!(parse_automation_nonce("automation-qx-a1"), None);
    }

    #[test]
    fn render_template_substitutes_payload_fields() {
        let payload = json!({"page_id": 42, "title": "Dishes", "flag": true});
        assert_eq!(
            render_template("Log: {{title}} ({{page_id}})", &payload),
            "Log: Dishes (42)"
        );
        assert_eq!(render_template("{{ flag }}", &payload), "true");
        // Unknown fields render empty; unterminated tokens pass through.
        assert_eq!(render_template("x{{missing}}y", &payload), "xy");
        assert_eq!(render_template("x{{oops", &payload), "x{{oops");
        assert_eq!(render_template("plain", &payload), "plain");
    }

    #[test]
    fn coerce_property_value_maps_json_to_typed_values() {
        assert_eq!(
            coerce_property_value(&PropertyType::Text, &json!("hi")).unwrap(),
            PropertyValue::Text("hi".to_string())
        );
        assert_eq!(
            coerce_property_value(&PropertyType::Number, &json!(2.5)).unwrap(),
            PropertyValue::Number(2.5)
        );
        assert_eq!(
            coerce_property_value(&PropertyType::Date, &json!(1770000000000u64)).unwrap(),
            PropertyValue::Date(1770000000000)
        );
        assert_eq!(
            coerce_property_value(&PropertyType::Checkbox, &json!(true)).unwrap(),
            PropertyValue::Checkbox(true)
        );
        assert_eq!(
            coerce_property_value(&PropertyType::MultiSelect, &json!(["a", "b"])).unwrap(),
            PropertyValue::MultiSelect(vec!["a".to_string(), "b".to_string()])
        );
        assert_eq!(
            coerce_property_value(&PropertyType::Relation, &json!([1, "2"])).unwrap(),
            PropertyValue::Relation(vec![1, 2])
        );
        assert!(coerce_property_value(&PropertyType::Number, &json!("nope")).is_err());
        assert!(coerce_property_value(&PropertyType::Ai, &json!("x")).is_err());
    }

    #[test]
    fn manual_trigger_config_validates_policy_and_fields() {
        let identity = "11".repeat(32);
        let config = json!({
            "invoker_policy": "identities",
            "allowed_invoker_identities": [identity],
            "allowed_input_fields": ["ask_id", "status"],
            "required_input_fields": ["ask_id"],
        });
        assert!(validate_manual_trigger_config(&config).is_ok());
        assert!(manual_invoker_allowed(&config, &"11".repeat(32), false, false).unwrap());
        assert!(!manual_invoker_allowed(&config, &"22".repeat(32), false, true).unwrap());
        assert!(manual_invoker_allowed(&config, &"22".repeat(32), true, false).unwrap());

        assert!(validate_manual_trigger_config(&json!({
            "invoker_policy": "identities",
            "allowed_invoker_identities": [],
        }))
        .is_err());
        assert!(validate_manual_trigger_config(&json!({
            "allowed_input_fields": ["invoked_by"],
        }))
        .is_err());
        assert!(validate_manual_trigger_config(&json!({
            "allowed_input_fields": ["status"],
            "required_input_fields": ["ask_id"],
        }))
        .is_err());
    }

    #[test]
    fn manual_input_is_allowlisted_and_server_metadata_is_stamped() {
        let config = json!({
            "invoker_policy": "workspace",
            "allowed_input_fields": ["ask_id", "decision"],
            "required_input_fields": ["ask_id"],
        });
        let input = json!({"ask_id": 42, "decision": "accept"});
        assert!(validate_manual_input(&config, &input).is_ok());
        assert!(validate_manual_input(&config, &json!({"decision": "accept"})).is_err());
        assert!(validate_manual_input(&config, &json!({"ask_id": 42, "extra": true})).is_err());
        assert!(validate_manual_input(&json!({}), &json!({"event_type": "spoof"})).is_err());

        let identity = Identity::from_byte_array([7; 32]);
        let payload = build_manual_payload(&input, 9, identity, "message:button:1").unwrap();
        assert_eq!(payload.get("event_type"), Some(&json!("manual")));
        assert_eq!(payload.get("automation_id"), Some(&json!(9)));
        assert_eq!(
            payload.get("invoked_by"),
            Some(&json!(identity.to_hex().to_string()))
        );
        assert_eq!(payload.get("idempotency_key"), Some(&json!("message:button:1")));
    }

