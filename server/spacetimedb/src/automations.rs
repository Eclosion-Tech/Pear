/// Explicitly invoke an enabled Manual automation.
///
/// The input is intentionally a flat JSON object: conditions and action
/// payload bindings can address its fields without a second expression
/// language. Invocation metadata is server-stamped and cannot be spoofed.
#[reducer]
pub fn invoke_automation(
    ctx: &ReducerContext,
    automation_id: u64,
    input_json: String,
    idempotency_key: String,
) -> Result<(), String> {
    let rule = ctx
        .db
        .automation_rule()
        .id()
        .find(automation_id)
        .ok_or("Automation rule not found")?;
    if !rule.enabled {
        return Err("Automation is disabled".to_string());
    }
    if rule.trigger_kind != AutomationTriggerKind::Manual {
        return Err("Only Manual automations can be invoked explicitly".to_string());
    }
    if rule_is_expired(ctx, &rule) {
        disable_automation_inner(ctx, rule);
        return Err("Automation has expired or reached its invocation limit".to_string());
    }
    validate_idempotency_key(&idempotency_key)?;
    if input_json.len() > MAX_MANUAL_INPUT_BYTES {
        return Err(format!(
            "Manual automation input exceeds {MAX_MANUAL_INPUT_BYTES} bytes"
        ));
    }

    let trigger_config = parse_json_object(&rule.trigger_config, "trigger_config")?;
    validate_manual_trigger_config(&trigger_config)?;
    let sender = ctx.sender();
    let is_creator_or_admin = sender == rule.created_by || sender_is_admin(ctx);
    let is_known_principal = is_known_workspace_principal(ctx, sender);
    if !manual_invoker_allowed(
        &trigger_config,
        &sender.to_hex().to_string(),
        is_creator_or_admin,
        is_known_principal,
    )? {
        return Err("Caller is not allowed to invoke this automation".to_string());
    }

    let input = parse_json_object(&input_json, "input_json")?;
    validate_manual_input(&trigger_config, &input)?;

    // Reducers are serialized and transactional, so this lookup + insert is
    // an atomic idempotency boundary without a second table or unique index.
    let duplicate = ctx
        .db
        .automation_event_queue()
        .by_rule()
        .filter(&automation_id)
        .any(|event| {
            event.invoked_by == Some(sender)
                && event.idempotency_key.as_deref() == Some(idempotency_key.as_str())
        });
    if duplicate {
        return Ok(());
    }

    let payload = build_manual_payload(&input, automation_id, sender, &idempotency_key)?;
    let queue_id = insert_event(
        ctx,
        &rule,
        AutomationTriggerKind::Manual,
        payload.to_string(),
        Some(sender),
        Some(idempotency_key),
    );
    try_process_inline(
        ctx,
        queue_id,
        inline_claim_label(&rule.mode, "manual-invocation"),
    )?;
    bump_manual_rule(ctx, automation_id);
    Ok(())
}

#[reducer]
pub fn delete_automation(ctx: &ReducerContext, automation_id: u64) -> Result<(), String> {
    let rule = require_rule_owner(ctx, automation_id, "delete automation")?;
    delete_schedule_jobs_for_rule(ctx, automation_id);
    for a in ctx
        .db
        .automation_action()
        .by_rule()
        .filter(&automation_id)
        .collect::<Vec<_>>()
    {
        ctx.db.automation_action().id().delete(a.id);
    }
    for c in ctx
        .db
        .automation_condition()
        .by_rule()
        .filter(&automation_id)
        .collect::<Vec<_>>()
    {
        ctx.db.automation_condition().id().delete(c.id);
    }
    for cap in ctx
        .db
        .automation_capability()
        .by_rule()
        .filter(&automation_id)
        .collect::<Vec<_>>()
    {
        ctx.db.automation_capability().id().delete(cap.id);
    }
    ctx.db.automation_rule().id().delete(rule.id);
    stop_cron_tick_if_unused(ctx);
    Ok(())
}

/// Process one queued event. In v0 this executes dry-run actions only.
#[reducer]
pub fn process_automation_event(ctx: &ReducerContext, queue_id: u64) -> Result<(), String> {
    let event = ctx
        .db
        .automation_event_queue()
        .id()
        .find(queue_id)
        .ok_or("Automation event not found")?;
    let rule = ctx
        .db
        .automation_rule()
        .id()
        .find(event.automation_id)
        .ok_or("Automation rule not found")?;
    require_creator_or_admin(ctx, rule.created_by, "process automation events")?;
    process_automation_event_inner(ctx, queue_id, Some("manual".to_string()))
}

/// Process pending events without needing a dedicated worker yet.
#[reducer]
pub fn process_pending_automation_events(ctx: &ReducerContext, limit: u32) -> Result<(), String> {
    let max = limit.clamp(1, 100);
    let events: Vec<u64> = ctx
        .db
        .automation_event_queue()
        .iter()
        .filter(|e| e.status == AutomationEventStatus::Pending)
        .take(max as usize)
        .map(|e| e.id)
        .collect();

    for queue_id in events {
        if let Some(event) = ctx.db.automation_event_queue().id().find(queue_id) {
            if let Some(rule) = ctx.db.automation_rule().id().find(event.automation_id) {
                require_creator_or_admin(ctx, rule.created_by, "process automation events")?;
                process_automation_event_inner(ctx, queue_id, Some("manual-batch".to_string()))?;
            }
        }
    }
    Ok(())
}

#[reducer]
pub fn run_scheduled_automation(
    ctx: &ReducerContext,
    job: AutomationScheduleJob,
) -> Result<(), String> {
    let Some(rule) = ctx.db.automation_rule().id().find(job.automation_id) else {
        return Ok(());
    };
    if !rule.enabled || rule.trigger_kind != AutomationTriggerKind::Scheduled {
        return Ok(());
    }
    if rule_is_expired(ctx, &rule) {
        disable_automation_inner(ctx, rule);
        return Ok(());
    }

    enqueue_scheduled_event(ctx, &rule, "schedule")?;
    bump_scheduled_rule(ctx, rule);
    Ok(())
}

#[reducer]
pub fn run_automation_cron_tick(
    ctx: &ReducerContext,
    _job: AutomationCronTick,
) -> Result<(), String> {
    let due: Vec<u64> = ctx
        .db
        .automation_rule()
        .iter()
        .filter(|r| {
            r.enabled
                && r.trigger_kind == AutomationTriggerKind::Scheduled
                && r.schedule_kind == AutomationScheduleKind::Cron
                && !rule_is_expired(ctx, r)
                && cron_rule_due(r, ctx.timestamp)
        })
        .map(|r| r.id)
        .collect();

    for automation_id in due {
        if let Some(rule) = ctx.db.automation_rule().id().find(automation_id) {
            enqueue_scheduled_event(ctx, &rule, "cron")?;
            bump_scheduled_rule(ctx, rule);
        }
    }
    stop_cron_tick_if_unused(ctx);
    Ok(())
}

