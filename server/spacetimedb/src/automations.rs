fn enqueue_matching_automations(
    ctx: &ReducerContext,
    trigger_kind: AutomationTriggerKind,
    payload: Value,
) -> Result<(), String> {
    let rules: Vec<AutomationRule> = ctx
        .db
        .automation_rule()
        .iter()
        .filter(|r| {
            r.enabled && r.trigger_kind == trigger_kind && trigger_matches_payload(r, &payload)
        })
        .collect();

    for rule in rules {
        let queue_id = insert_event(
            ctx,
            &rule,
            trigger_kind.clone(),
            payload.to_string(),
            None,
            None,
        );
        try_process_inline(ctx, queue_id, inline_claim_label(&rule.mode, "inline"))?;
    }
    Ok(())
}

/// Process an event inline (inside the triggering transaction) unless the
/// recursion-depth cap is reached, in which case the event stays Pending.
fn try_process_inline(ctx: &ReducerContext, queue_id: u64, claimed_by: String) -> Result<(), String> {
    let depth = INLINE_EXEC_DEPTH.with(Cell::get);
    if depth >= MAX_INLINE_EXEC_DEPTH {
        log::warn!(
            "automation event {queue_id}: inline execution depth {depth} reached; leaving Pending"
        );
        return Ok(());
    }
    INLINE_EXEC_DEPTH.with(|d| d.set(depth + 1));
    let result = process_automation_event_inner(ctx, queue_id, Some(claimed_by));
    INLINE_EXEC_DEPTH.with(|d| d.set(depth));
    result
}

fn inline_claim_label(mode: &AutomationMode, source: &str) -> String {
    match mode {
        AutomationMode::DryRun => format!("{source}-dry-run"),
        AutomationMode::Live => format!("{source}-live"),
    }
}

fn enqueue_scheduled_event(
    ctx: &ReducerContext,
    rule: &AutomationRule,
    source: &str,
) -> Result<(), String> {
    let payload = json!({
        "event_type": "scheduled",
        "source": source,
        "automation_id": rule.id,
        "tick_count": rule.tick_count + 1,
        "scheduled_at_micros": ctx.timestamp.to_micros_since_unix_epoch(),
    });
    let queue_id = insert_event(
        ctx,
        rule,
        AutomationTriggerKind::Scheduled,
        payload.to_string(),
        None,
        None,
    );
    try_process_inline(ctx, queue_id, inline_claim_label(&rule.mode, source))?;
    Ok(())
}

fn insert_event(
    ctx: &ReducerContext,
    rule: &AutomationRule,
    trigger_kind: AutomationTriggerKind,
    trigger_payload: String,
    invoked_by: Option<Identity>,
    idempotency_key: Option<String>,
) -> u64 {
    let row = ctx
        .db
        .automation_event_queue()
        .insert(AutomationEventQueue {
            id: next_automation_event_queue_id(ctx),
            automation_id: rule.id,
            trigger_kind,
            trigger_payload,
            status: AutomationEventStatus::Pending,
            attempts: 0,
            claimed_by: None,
            error: None,
            created_at: ctx.timestamp,
            updated_at: ctx.timestamp,
            invoked_by,
            idempotency_key,
        });
    row.id
}

fn process_automation_event_inner(
    ctx: &ReducerContext,
    queue_id: u64,
    claimed_by: Option<String>,
) -> Result<(), String> {
    let event = ctx
        .db
        .automation_event_queue()
        .id()
        .find(queue_id)
        .ok_or("Automation event not found")?;
    if event.status == AutomationEventStatus::Completed
        || event.status == AutomationEventStatus::Failed
        || event.status == AutomationEventStatus::Skipped
    {
        return Ok(());
    }

    let rule = ctx
        .db
        .automation_rule()
        .id()
        .find(event.automation_id)
        .ok_or("Automation rule not found")?;
    let payload = parse_json_object(&event.trigger_payload, "trigger_payload")?;
    let effective_run_as = event.invoked_by.unwrap_or(rule.run_as);

    ctx.db
        .automation_event_queue()
        .id()
        .update(AutomationEventQueue {
            status: AutomationEventStatus::Running,
            attempts: event.attempts + 1,
            claimed_by,
            updated_at: ctx.timestamp,
            ..event
        });

    if !conditions_match(ctx, rule.id, &payload)? {
        insert_run_log(
            ctx,
            queue_id,
            None,
            true,
            true,
            "Conditions did not match; no actions would run".to_string(),
            json!({"condition_result":"skipped"}).to_string(),
        );
        update_event_status(ctx, queue_id, AutomationEventStatus::Skipped, None);
        return Ok(());
    }

    let mut actions: Vec<AutomationAction> = ctx
        .db
        .automation_action()
        .by_rule()
        .filter(&rule.id)
        .collect();
    actions.sort_by_key(|a| a.order);

    if actions.is_empty() {
        insert_run_log(
            ctx,
            queue_id,
            None,
            true,
            true,
            "No actions configured".to_string(),
            "{}".to_string(),
        );
        update_event_status(ctx, queue_id, AutomationEventStatus::Completed, None);
        return Ok(());
    }

    if rule.mode == AutomationMode::DryRun {
        for action in actions {
            insert_run_log(
                ctx,
                queue_id,
                Some(action.id),
                true,
                true,
                format!("Would execute {}", action_kind_name(&action.action_kind)),
                json!({
                    "action_kind": action_kind_name(&action.action_kind),
                    "config": parse_json_object(&action.config, "action config")?,
                    "trigger_payload": payload,
                })
                .to_string(),
            );
        }
        update_event_status(ctx, queue_id, AutomationEventStatus::Completed, None);
        return Ok(());
    }

    // Live execution: event triggers use rule.run_as; Manual triggers use the
    // recorded invoker so generated controls cannot borrow the author's ACLs.
    // An action failure logs and marks the event Failed but returns Ok — an
    // Err here would roll back the triggering transaction (and the logs).
    //
    // `OrchaJob` is asynchronous: the reducer only enqueues the job, and the
    // worker does the real work later. The event therefore stays `Running`
    // until every spawned job reaches a terminal state — `on_orcha_job_finished`
    // (called from the orcha completion path) logs the outcome and closes it.
    let mut awaiting_jobs = false;
    for action in actions {
        match execute_live_action(ctx, &rule, effective_run_as, &action, queue_id, &payload) {
            Ok(result) => {
                let is_job = matches!(action.action_kind, AutomationActionKind::OrchaJob);
                let message = if is_job {
                    awaiting_jobs = true;
                    match json_u64(result.get("job_id")) {
                        Some(job_id) => {
                            format!("Queued OrchaJob #{job_id} — waiting for the worker to run it")
                        }
                        None => "Queued OrchaJob — waiting for the worker to run it".to_string(),
                    }
                } else {
                    format!("Executed {}", action_kind_name(&action.action_kind))
                };
                insert_run_log(
                    ctx,
                    queue_id,
                    Some(action.id),
                    true,
                    false,
                    message,
                    result.to_string(),
                );
            }
            Err(err) => {
                insert_run_log(
                    ctx,
                    queue_id,
                    Some(action.id),
                    false,
                    false,
                    format!("{} failed: {err}", action_kind_name(&action.action_kind)),
                    json!({ "error": err }).to_string(),
                );
                update_event_status(ctx, queue_id, AutomationEventStatus::Failed, Some(err));
                return Ok(());
            }
        }
    }
    if awaiting_jobs {
        return Ok(());
    }
    update_event_status(ctx, queue_id, AutomationEventStatus::Completed, None);
    Ok(())
}

/// Nonce `execute_orcha_job` stamps on the jobs it spawns, so the run log, the
/// UI, and the completion hook can all find the job for a given action run.
fn automation_job_nonce(queue_id: u64, action_id: u64) -> String {
    format!("automation-q{queue_id}-a{action_id}")
}

/// Inverse of [`automation_job_nonce`]: `(queue_id, action_id)`, or `None` for
/// jobs that weren't spawned by an automation.
pub(crate) fn parse_automation_nonce(nonce: &str) -> Option<(u64, u64)> {
    let rest = nonce.strip_prefix("automation-q")?;
    let (queue, action) = rest.split_once("-a")?;
    Some((queue.parse().ok()?, action.parse().ok()?))
}

/// Called from `check_orcha_job_completion` when a job transitions to a
/// terminal state. For automation-spawned jobs this records the per-task
/// outcome in the run log and — once every job spawned by the same event is
/// terminal — moves the event from `Running` to `Completed` / `Failed`.
pub(crate) fn on_orcha_job_finished(
    ctx: &ReducerContext,
    job_id: u64,
    nonce: &str,
    tasks: &[OrchaTask],
    any_failed: bool,
) {
    let Some((queue_id, action_id)) = parse_automation_nonce(nonce) else {
        return;
    };
    let done = tasks.iter().filter(|t| t.status == "done").count();
    let failed = tasks.iter().filter(|t| t.status == "failed").count();
    let first_error = tasks
        .iter()
        .find(|t| t.status == "failed")
        .and_then(|t| t.result.as_deref())
        .map(|r| truncate_chars(r, 300));
    let message = if any_failed {
        format!(
            "OrchaJob #{job_id} failed: {failed} of {} task(s) failed{}",
            tasks.len(),
            first_error
                .as_deref()
                .map(|e| format!(" — {e}"))
                .unwrap_or_default()
        )
    } else {
        format!(
            "OrchaJob #{job_id} completed: {done}/{} task(s) done",
            tasks.len()
        )
    };
    let summary = json!({
        "job_id": job_id,
        "nonce": nonce,
        "status": if any_failed { "failed" } else { "complete" },
        "tasks": tasks
            .iter()
            .map(|t| json!({
                "id": t.id,
                "task_type": t.task_type,
                "status": t.status,
                "description": truncate_chars(&t.description, 200),
                "result": t.result.as_deref().map(|r| tail_chars(r, 400)),
            }))
            .collect::<Vec<_>>(),
    });
    insert_run_log(
        ctx,
        queue_id,
        Some(action_id),
        !any_failed,
        false,
        message.clone(),
        summary.to_string(),
    );

    let Some(event) = ctx.db.automation_event_queue().id().find(queue_id) else {
        return;
    };
    // Only the async-wait state is ours to close; a synchronous action failure
    // may already have marked the event Failed.
    if !matches!(event.status, AutomationEventStatus::Running) {
        return;
    }
    // A rule may spawn several jobs from one event (one per OrchaJob action):
    // the event closes when the last one lands, failing if any of them failed.
    let prefix = format!("automation-q{queue_id}-a");
    let siblings: Vec<_> = ctx
        .db
        .orcha_job()
        .iter()
        .filter(|j| j.nonce.as_deref().is_some_and(|n| n.starts_with(&prefix)))
        .collect();
    if siblings.iter().any(|j| j.status == "executing") {
        return;
    }
    if siblings.iter().any(|j| j.status == "failed") {
        let error = if any_failed {
            message
        } else {
            "An OrchaJob spawned by this run failed".to_string()
        };
        update_event_status(ctx, queue_id, AutomationEventStatus::Failed, Some(error));
    } else {
        update_event_status(ctx, queue_id, AutomationEventStatus::Completed, None);
    }
}

/// Execute one live action. Returns a JSON result for the run log, or an error
/// string (which fails the event without rolling back the transaction).
fn execute_live_action(
    ctx: &ReducerContext,
    rule: &AutomationRule,
    effective_run_as: Identity,
    action: &AutomationAction,
    queue_id: u64,
    payload: &Value,
) -> Result<Value, String> {
    let config = parse_json_object(&action.config, "action config")?;
    match action.action_kind {
        AutomationActionKind::CreatePage => {
            execute_create_page(ctx, rule, effective_run_as, &config, payload)
        }
        AutomationActionKind::UpdateProperty => {
            execute_update_property(ctx, rule, effective_run_as, &config, payload)
        }
        AutomationActionKind::OrchaJob => execute_orcha_job(
            ctx,
            effective_run_as,
            action.id,
            queue_id,
            &config,
            payload,
        ),
        AutomationActionKind::HttpRequest | AutomationActionKind::SendEmail => Err(
            "action requires the worker executor and cannot run in-module; keep the rule in DryRun"
                .to_string(),
        ),
    }
}

fn execute_create_page(
    ctx: &ReducerContext,
    rule: &AutomationRule,
    effective_run_as: Identity,
    config: &Value,
    payload: &Value,
) -> Result<Value, String> {
    let parent_id = json_u64(config.get("parent_id"));
    let title_template = config
        .get("title_template")
        .and_then(Value::as_str)
        .unwrap_or("Automation page");
    let title = render_template(title_template, payload).trim().to_string();
    if title.is_empty() {
        return Err("rendered title is empty".to_string());
    }
    if let Some(pid) = parent_id {
        let parent = ctx
            .db
            .page()
            .id()
            .find(pid)
            .ok_or(format!("parent page {pid} not found"))?;
        if parent.deleted_at.is_some() {
            return Err(format!("parent page {pid} is deleted"));
        }
        if !can_write_page(ctx, pid, effective_run_as) {
            return Err(format!(
                "execution principal lacks write access on parent page {pid}"
            ));
        }
    }
    let page_id = create_component_tree_page_inner(
        ctx,
        parent_id,
        PageType::Doc,
        title.clone(),
        ActorType::Agent(format!("automation:{}", rule.id)),
    )?;
    Ok(json!({ "page_id": page_id, "title": title }))
}

fn execute_update_property(
    ctx: &ReducerContext,
    rule: &AutomationRule,
    effective_run_as: Identity,
    config: &Value,
    payload: &Value,
) -> Result<Value, String> {
    let property_definition_id = json_u64(config.get("property_definition_id"))
        .ok_or("action config.property_definition_id is required")?;
    // Target page: explicit config.page_id, else the payload field named by
    // config.page_id_field (default "page_id" — the common event-trigger case).
    let page_id = match json_u64(config.get("page_id")) {
        Some(id) => id,
        None => {
            let field = config
                .get("page_id_field")
                .and_then(Value::as_str)
                .unwrap_or("page_id");
            json_u64(payload.get(field)).ok_or(format!(
                "trigger payload has no usable '{field}' field to select a target page"
            ))?
        }
    };
    ctx.db
        .page()
        .id()
        .find(page_id)
        .ok_or(format!("page {page_id} not found"))?;
    if !can_write_page(ctx, page_id, effective_run_as) {
        return Err(format!(
            "execution principal lacks write access on page {page_id}"
        ));
    }
    let def = ctx
        .db
        .property_definition()
        .id()
        .find(property_definition_id)
        .ok_or(format!(
            "property definition {property_definition_id} not found"
        ))?;
    let raw = resolve_property_action_value(config, payload)?;
    let value = coerce_property_value(&def.property_type, raw)?;
    set_property_value_inner(
        ctx,
        page_id,
        property_definition_id,
        value,
        ActorType::Agent(format!("automation:{}", rule.id)),
    )?;
    Ok(json!({
        "page_id": page_id,
        "property_definition_id": property_definition_id,
    }))
}

fn execute_orcha_job(
    ctx: &ReducerContext,
    effective_run_as: Identity,
    action_id: u64,
    queue_id: u64,
    config: &Value,
    payload: &Value,
) -> Result<Value, String> {
    let prompt_template = config
        .get("prompt_template")
        .and_then(Value::as_str)
        .ok_or("action config.prompt_template is required")?;
    let prompt = render_template(prompt_template, payload).trim().to_string();
    if prompt.is_empty() {
        return Err("rendered prompt is empty".to_string());
    }
    let page_id = config
        .get("page_id_field")
        .and_then(Value::as_str)
        .and_then(|f| json_u64(payload.get(f)))
        .or_else(|| json_u64(payload.get("page_id")));
    // The AI user whose credentials and governed connection run this job. An
    // explicit `config.ai_user_id` wins; otherwise the run-as principal itself
    // when it is an AI user — "Runs as Kira" means the job is Kira's, using her
    // key. Without either, the worker falls back to its default provider, which
    // a deployment may not configure at all (the job then fails at claim time).
    let ai_user_id = json_u64(config.get("ai_user_id")).or_else(|| {
        ctx.db
            .ai_user_config()
            .identity()
            .find(effective_run_as)
            .map(|c| c.id)
    });
    if let Some(id) = ai_user_id {
        ctx.db
            .ai_user_config()
            .id()
            .find(id)
            .ok_or(format!("AI user {id} not found"))?;
        if ai_user_at_hard_cap(ctx, id) {
            return Err(format!("AI user {id} is at its monthly token cap"));
        }
    }
    let tier = config
        .get("tier")
        .and_then(Value::as_str)
        .map(str::to_string);
    // Same single-task graph the worker's `delegate` tool creates; the nonce
    // lets observers read back exactly this job.
    let nonce = automation_job_nonce(queue_id, action_id);
    let task_graph = json!([{
        "description": prompt,
        "task_type": "orchestrate",
        "depends_on": [],
        "required_capabilities": ["orchestrate"],
    }]);
    let job_id = create_job_inner(
        ctx,
        effective_run_as.to_hex().to_string(),
        prompt,
        page_id,
        ai_user_id,
        tier,
        nonce.clone(),
        None,
        task_graph.to_string(),
    )?;
    Ok(json!({
        "nonce": nonce,
        "page_id": page_id,
        "job_id": job_id,
        "ai_user_id": ai_user_id,
    }))
}

fn resolve_property_action_value<'a>(
    config: &'a Value,
    payload: &'a Value,
) -> Result<&'a Value, String> {
    if let Some(field) = config.get("value_field").and_then(Value::as_str) {
        let field = field.trim();
        if field.is_empty() {
            return Err("action config.value_field cannot be empty".to_string());
        }
        return payload.get(field).ok_or_else(|| {
            format!("trigger payload has no '{field}' field to use as the property value")
        });
    }
    config
        .get("value")
        .ok_or("action config.value or value_field is required".to_string())
}

/// Coerce a JSON action-config value into the typed `PropertyValue` matching
/// the target column. Computed columns (Ai) cannot be set by automations.
fn coerce_property_value(
    property_type: &PropertyType,
    raw: &Value,
) -> Result<PropertyValue, String> {
    fn as_string(raw: &Value) -> Option<String> {
        raw.as_str().map(str::to_string)
    }
    fn as_string_vec(raw: &Value) -> Option<Vec<String>> {
        raw.as_array()?
            .iter()
            .map(|v| v.as_str().map(str::to_string))
            .collect()
    }
    fn as_u64_vec(raw: &Value) -> Option<Vec<u64>> {
        raw.as_array()?.iter().map(|v| json_u64(Some(v))).collect()
    }
    match property_type {
        PropertyType::Text => as_string(raw)
            .map(PropertyValue::Text)
            .ok_or("value must be a string for a Text property".to_string()),
        PropertyType::Url => as_string(raw)
            .map(PropertyValue::Url)
            .ok_or("value must be a string for a Url property".to_string()),
        PropertyType::Select => as_string(raw)
            .map(PropertyValue::Select)
            .ok_or("value must be a string for a Select property".to_string()),
        PropertyType::Number => raw
            .as_f64()
            .map(PropertyValue::Number)
            .ok_or("value must be a number for a Number property".to_string()),
        PropertyType::Date => json_u64(Some(raw))
            .map(PropertyValue::Date)
            .ok_or("value must be a unix-ms number for a Date property".to_string()),
        PropertyType::Checkbox => raw
            .as_bool()
            .map(PropertyValue::Checkbox)
            .ok_or("value must be a boolean for a Checkbox property".to_string()),
        PropertyType::MultiSelect => as_string_vec(raw)
            .map(PropertyValue::MultiSelect)
            .ok_or("value must be an array of strings for a MultiSelect property".to_string()),
        PropertyType::Person => as_string_vec(raw)
            .map(PropertyValue::Person)
            .ok_or("value must be an array of identity strings for a Person property".to_string()),
        PropertyType::Relation => as_u64_vec(raw)
            .map(PropertyValue::Relation)
            .ok_or("value must be an array of page ids for a Relation property".to_string()),
        PropertyType::File => {
            Err("File properties cannot be set by automations yet".to_string())
        }
        _ => Err("computed property types cannot be set by automations".to_string()),
    }
}

/// Replace `{{field}}` tokens with the matching top-level trigger-payload
/// scalar; unknown fields render as empty. Unterminated tokens pass through.
fn render_template(template: &str, payload: &Value) -> String {
    let mut out = String::with_capacity(template.len());
    let mut rest = template;
    while let Some(start) = rest.find("{{") {
        out.push_str(&rest[..start]);
        let after = &rest[start + 2..];
        match after.find("}}") {
            Some(end) => {
                let key = after[..end].trim();
                if let Some(v) = payload.get(key) {
                    out.push_str(&json_scalar_as_string(v));
                }
                rest = &after[end + 2..];
            }
            None => {
                out.push_str(&rest[start..]);
                rest = "";
            }
        }
    }
    out.push_str(rest);
    out
}

