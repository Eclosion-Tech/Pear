#[reducer]
pub fn create_automation_draft(
    ctx: &ReducerContext,
    name: String,
    trigger_kind: AutomationTriggerKind,
    trigger_config: String,
    schedule_kind: AutomationScheduleKind,
    schedule_config: String,
    timezone: String,
    canonical_description: String,
) -> Result<(), String> {
    if name.trim().is_empty() {
        return Err("Automation name cannot be empty".to_string());
    }
    parse_json_object(&trigger_config, "trigger_config")?;
    parse_json_object(&schedule_config, "schedule_config")?;

    ctx.db.automation_rule().insert(AutomationRule {
        id: next_automation_rule_id(ctx),
        name: name.trim().to_string(),
        enabled: false,
        mode: AutomationMode::DryRun,
        trigger_kind,
        trigger_config,
        schedule_kind,
        schedule_config,
        timezone: normalize_timezone(timezone),
        next_run_at: None,
        last_run_at: None,
        max_ticks: None,
        tick_count: 0,
        expires_at: None,
        run_as: ctx.sender(),
        created_by: ctx.sender(),
        created_at: ctx.timestamp,
        updated_at: ctx.timestamp,
        canonical_description,
    });
    Ok(())
}

#[reducer]
pub fn update_automation_rule(
    ctx: &ReducerContext,
    automation_id: u64,
    name: String,
    trigger_kind: AutomationTriggerKind,
    trigger_config: String,
    schedule_kind: AutomationScheduleKind,
    schedule_config: String,
    timezone: String,
    canonical_description: String,
) -> Result<(), String> {
    parse_json_object(&trigger_config, "trigger_config")?;
    parse_json_object(&schedule_config, "schedule_config")?;
    let rule = require_rule_owner(ctx, automation_id, "update automation")?;
    ctx.db.automation_rule().id().update(AutomationRule {
        name: name.trim().to_string(),
        trigger_kind,
        trigger_config,
        schedule_kind,
        schedule_config,
        timezone: normalize_timezone(timezone),
        canonical_description,
        enabled: false,
        next_run_at: None,
        updated_at: ctx.timestamp,
        ..rule
    });
    delete_schedule_jobs_for_rule(ctx, automation_id);
    Ok(())
}

