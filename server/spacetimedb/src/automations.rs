/// A user- or AI-authored automation rule. Rules default to dry-run and disabled.
#[table(accessor = automation_rule, public)]
pub struct AutomationRule {
    #[primary_key]
    #[auto_inc]
    pub id: u64,
    pub name: String,
    pub enabled: bool,
    pub mode: AutomationMode,
    pub trigger_kind: AutomationTriggerKind,
    /// JSON config scoped to the trigger. Examples:
    /// - PageCreated: {"parent_id": 12}
    /// - PropertyChanged: {"property_definition_id": 42}
    pub trigger_config: String,
    pub schedule_kind: AutomationScheduleKind,
    /// JSON schedule config. Interval: {"interval_seconds": 3600}; one-shot:
    /// {"run_at_micros": 1770000000000000}; cron: {"expression": "0 9 * * 1"}.
    pub schedule_config: String,
    /// Stored now so the review surface is future-proof. Cron v0 evaluates in UTC.
    pub timezone: String,
    pub next_run_at: Option<Timestamp>,
    pub last_run_at: Option<Timestamp>,
    pub max_ticks: Option<u64>,
    pub tick_count: u64,
    pub expires_at: Option<Timestamp>,
    /// The principal whose authority live execution will use. Defaults to creator.
    pub run_as: Identity,
    pub created_by: Identity,
    pub created_at: Timestamp,
    pub updated_at: Timestamp,
    /// Canonical human review string, generated by UI or AI alongside the graph.
    pub canonical_description: String,
}

